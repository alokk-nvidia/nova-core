/// Marker type representing the absence of a reply for a command. Commands using this as their
/// reply type are sent using [`Cmdq::send_command_no_wait`].
pub(crate) struct NoReply;

/// Trait implemented by types representing a command to send to the GSP.
///
/// The main purpose of this trait is to provide [`Cmdq`] with the information it needs to send
/// a given command.
///
/// [`CommandToGsp::init`] in particular is responsible for initializing the command directly
/// into the space reserved for it in the command queue buffer.
///
/// Some commands may be followed by a variable-length payload. For these, the
/// [`CommandToGsp::variable_payload_len`] and [`CommandToGsp::init_variable_payload`] need to be
/// defined as well.
pub(crate) trait CommandToGsp {
    /// Function identifying this command to the GSP.
    const FUNCTION: MsgFunction;

    /// Whether this command is async (fire-and-forget), meaning no response is expected from GSP.
    ///
    /// Async commands get `rpc.sequence` set to 0. Sync commands get `rpc.sequence`
    /// set to the sequence counter, matching Open RM.
    const IS_ASYNC: bool = false;

    /// Type generated by [`CommandToGsp::init`], to be written into the command queue buffer.
    type Command: FromBytes + AsBytes;

    /// Type of the reply expected from the GSP, or [`NoReply`] for commands that don't
    /// have a reply.
    type Reply;

    /// Error type returned by [`CommandToGsp::init`].
    type InitError;

    /// In-place command initializer responsible for filling the command in the command queue
    /// buffer.
    fn init(&self) -> impl Init<Self::Command, Self::InitError>;

    /// Size of the variable-length payload following the command structure generated by
    /// [`CommandToGsp::init`].
    ///
    /// Most commands don't have a variable-length payload, so this is zero by default.
    fn variable_payload_len(&self) -> usize {
        0
    }

    /// Method initializing the variable-length payload.
    ///
    /// The command buffer is circular, which means that we may need to jump back to its beginning
    /// while in the middle of a command. For this reason, the variable-length payload is
    /// initialized using a [`SBufferIter`].
    ///
    /// This method will receive a buffer of the length returned by
    /// [`CommandToGsp::variable_payload_len`], and must write every single byte of it. Leaving
    /// unwritten space will lead to an error.
    ///
    /// Most commands don't have a variable-length payload, so this does nothing by default.
    fn init_variable_payload(
        &self,
        _dst: &mut SBufferIter<core::array::IntoIter<&mut [u8], 2>>,
    ) -> Result {
        Ok(())
    }

    /// Total size of the command (including its variable-length payload) without the
    /// [`GspMsgElement`] header.
    fn size(&self) -> usize {
        size_of::<Self::Command>() + self.variable_payload_len()
    }
}

/// Trait representing messages received from the GSP.
///
/// This trait tells [`Cmdq::receive_msg`] how it can receive a given type of message.
pub(crate) trait MessageFromGsp: Sized {
    /// Function identifying this message from the GSP.
    const FUNCTION: MsgFunction;

    /// Error type returned by [`MessageFromGsp::read`].
    type InitError;

    /// Type containing the raw message to be read from the message queue.
    type Message: FromBytes;

    /// Method reading the message from the message queue and returning it.
    ///
    /// From a `Self::Message` and a [`SBufferIter`], constructs an instance of `Self` and returns
    /// it.
    fn read(
        msg: &Self::Message,
        sbuffer: &mut SBufferIter<core::array::IntoIter<&[u8], 2>>,
    ) -> Result<Self, Self::InitError>;
}

/// Number of GSP pages making the [`Msgq`].
pub(crate) const MSGQ_NUM_PAGES: u32 = 0x3f;

/// Circular buffer of a [`Msgq`].
///
/// This area of memory is to be shared between the driver and the GSP to exchange commands or
/// messages.
#[repr(C, align(0x1000))]
#[derive(Debug)]
struct MsgqData {
    data: [[u8; GSP_PAGE_SIZE]; num::u32_as_usize(MSGQ_NUM_PAGES)],
}

// Annoyingly we are forced to use a literal to specify the alignment of
// `MsgqData`, so check that it corresponds to the actual GSP page size here.
static_assert!(align_of::<MsgqData>() == GSP_PAGE_SIZE);

/// Unidirectional message queue.
///
/// Contains the data for a message queue, that either the driver or GSP writes to.
///
/// Note that while the write pointer of `tx` corresponds to the `msgq` of the same instance, the
/// read pointer of `rx` actually refers to the `Msgq` owned by the other side.
/// This design ensures that only the driver or GSP ever writes to a given instance of this struct.
#[repr(C)]
// There is no struct defined for this in the open-gpu-kernel-source headers.
// Instead it is defined by code in `GspMsgQueuesInit()`.
struct Msgq {
    /// Header for sending messages, including the write pointer.
    tx: MsgqTxHeader,
    /// Header for receiving messages, including the read pointer.
    rx: MsgqRxHeader,
    /// The message queue proper.
    msgq: MsgqData,
}

/// Structure shared between the driver and the GSP and containing the command and message queues.
#[repr(C)]
struct GspMem {
    /// Self-mapping page table entries.
    ptes: PteArray<{ Self::PTE_ARRAY_SIZE }>,
    /// CPU queue: the driver writes commands here, and the GSP reads them. It also contains the
    /// write and read pointers that the CPU updates. This means that the read pointer here is an
    /// index into the GSP queue.
    ///
    /// This member is read-only for the GSP.
    cpuq: Msgq,
    /// GSP queue: the GSP writes messages here, and the driver reads them. It also contains the
    /// write and read pointers that the GSP updates. This means that the read pointer here is an
    /// index into the CPU queue.
    ///
    /// This member is read-only for the driver.
    gspq: Msgq,
}

impl GspMem {
    const PTE_ARRAY_SIZE: usize = GSP_PAGE_SIZE / size_of::<u64>();
}

// SAFETY: These structs don't meet the no-padding requirements of AsBytes but
// that is not a problem because they are not used outside the kernel.
unsafe impl AsBytes for GspMem {}

// SAFETY: These structs don't meet the no-padding requirements of FromBytes but
// that is not a problem because they are not used outside the kernel.
unsafe impl FromBytes for GspMem {}

/// Wrapper around [`GspMem`] to share it with the GPU using a [`Coherent`].
///
/// This provides the low-level functionality to communicate with the GSP, including allocation of
/// queue space to write messages to and management of read/write pointers.
///
/// This is shared with the GSP, with clear ownership rules regarding the command queues:
///
/// * The driver owns (i.e. can write to) the part of the CPU message queue between the CPU write
///   pointer and the GSP read pointer. This region is returned by [`Self::driver_write_area`].
/// * The driver owns (i.e. can read from) the part of the GSP message queue between the CPU read
///   pointer and the GSP write pointer. This region is returned by [`Self::driver_read_area`].
struct DmaGspMem(Coherent<GspMem>);

impl DmaGspMem {
    /// Allocate a new instance and map it for `dev`.
    fn new(dev: &device::Device<device::Bound>) -> Result<Self> {
        const MSGQ_SIZE: u32 = num::usize_into_u32::<{ size_of::<Msgq>() }>();
        const MSG_SIZE: u32 = num::usize_into_u32::<GSP_PAGE_SIZE>();
        const ENTRY_OFF: u32 = num::usize_into_u32::<{ mem::offset_of!(Msgq, msgq) }>();

        let mut gsp_mem = CoherentBox::<GspMem>::zeroed(dev, GFP_KERNEL)?;
        gsp_mem.cpuq.tx = MsgqTxHeader::new_v2(MSGQ_SIZE, MSG_SIZE, MSGQ_NUM_PAGES, ENTRY_OFF);

        let gsp_mem: Coherent<_> = gsp_mem.into();
        let start = gsp_mem.dma_handle();
        PteArray::init(io_project!(gsp_mem, .ptes), start)?;

        Ok(Self(gsp_mem))
    }
}

// v0 ring helpers retained until the cleanup commits delete them along with
// `gsp_mem` and the v0 wire-protocol types.
#[expect(dead_code)]
impl DmaGspMem {
    /// Returns the region of the CPU message queue that the driver is currently allowed to write
    /// to.
    ///
    /// As the message queue is a circular buffer, the region may be discontiguous in memory. In
    /// that case the second slice will have a non-zero length.
    fn driver_write_area(&mut self) -> (&mut [[u8; GSP_PAGE_SIZE]], &mut [[u8; GSP_PAGE_SIZE]]) {
        let tx = self.cpu_write_ptr() as usize;
        let rx = self.gsp_read_ptr() as usize;

        // SAFETY:
        // - We will only access the driver-owned part of the shared memory.
        // - Per the safety statement of the function, no concurrent access will be performed.
        let gsp_mem = unsafe { &mut *self.0.as_mut() };
        // PANIC: per the invariant of `cpu_write_ptr`, `tx` is `< MSGQ_NUM_PAGES`.
        let (before_tx, after_tx) = gsp_mem.cpuq.msgq.data.split_at_mut(tx);

        // The area starting at `tx` and ending at `rx - 2` modulo MSGQ_NUM_PAGES, inclusive,
        // belongs to the driver for writing.

        if rx == 0 {
            // Since `rx` is zero, leave an empty slot at end of the buffer.
            let last = after_tx.len() - 1;
            (&mut after_tx[..last], &mut [])
        } else if rx <= tx {
            // The area is discontiguous and we leave an empty slot before `rx`.
            // PANIC:
            // - The index `rx - 1` is non-negative because `rx != 0` in this branch.
            // - The index does not exceed `before_tx.len()` (which equals `tx`) because
            //   `rx <= tx` in this branch.
            (after_tx, &mut before_tx[..(rx - 1)])
        } else {
            // The area is contiguous and we leave an empty slot before `rx`.
            // PANIC:
            // - The index `rx - tx - 1` is non-negative because `rx > tx` in this branch.
            // - The index does not exceed `after_tx.len()` (which is `MSGQ_NUM_PAGES - tx`)
            //   because `rx < MSGQ_NUM_PAGES` by the `gsp_read_ptr` invariant.
            (&mut after_tx[..(rx - tx - 1)], &mut [])
        }
    }

    /// Returns the size of the region of the CPU message queue that the driver is currently allowed
    /// to write to, in bytes.
    fn driver_write_area_size(&self) -> usize {
        let tx = self.cpu_write_ptr();
        let rx = self.gsp_read_ptr();

        // `rx` and `tx` are both in `0..MSGQ_NUM_PAGES` per the invariants of `gsp_read_ptr` and
        // `cpu_write_ptr`. The minimum value case is where `rx == 0` and `tx == MSGQ_NUM_PAGES -
        // 1`, which gives `0 + MSGQ_NUM_PAGES - (MSGQ_NUM_PAGES - 1) - 1 == 0`.
        let slots = (rx + MSGQ_NUM_PAGES - tx - 1) % MSGQ_NUM_PAGES;
        num::u32_as_usize(slots) * GSP_PAGE_SIZE
    }

    /// Returns the region of the GSP message queue that the driver is currently allowed to read
    /// from.
    ///
    /// As the message queue is a circular buffer, the region may be discontiguous in memory. In
    /// that case the second slice will have a non-zero length.
    fn driver_read_area(&self) -> (&[[u8; GSP_PAGE_SIZE]], &[[u8; GSP_PAGE_SIZE]]) {
        let tx = self.gsp_write_ptr() as usize;
        let rx = self.cpu_read_ptr() as usize;

        // SAFETY:
        // - We will only access the driver-owned part of the shared memory.
        // - Per the safety statement of the function, no concurrent access will be performed.
        let gsp_mem = unsafe { &*self.0.as_ptr() };
        let data = &gsp_mem.gspq.msgq.data;

        // The area starting at `rx` and ending at `tx - 1` modulo MSGQ_NUM_PAGES, inclusive,
        // belongs to the driver for reading.
        // PANIC:
        // - per the invariant of `cpu_read_ptr`, `rx < MSGQ_NUM_PAGES`
        // - per the invariant of `gsp_write_ptr`, `tx < MSGQ_NUM_PAGES`
        if rx <= tx {
            // The area is contiguous.
            (&data[rx..tx], &[])
        } else {
            // The area is discontiguous.
            (&data[rx..], &data[..tx])
        }
    }

    // Returns the index of the memory page the GSP will write the next message to.
    //
    // # Invariants
    //
    // - The returned value is within `0..MSGQ_NUM_PAGES`.
    fn gsp_write_ptr(&self) -> u32 {
        MsgqTxHeader::write_ptr(io_project!(self.0, .gspq.tx)) % MSGQ_NUM_PAGES
    }

    // Returns the index of the memory page the GSP will read the next command from.
    //
    // # Invariants
    //
    // - The returned value is within `0..MSGQ_NUM_PAGES`.
    fn gsp_read_ptr(&self) -> u32 {
        MsgqRxHeader::read_ptr(io_project!(self.0, .gspq.rx)) % MSGQ_NUM_PAGES
    }

    // Returns the index of the memory page the CPU can read the next message from.
    //
    // # Invariants
    //
    // - The returned value is within `0..MSGQ_NUM_PAGES`.
    fn cpu_read_ptr(&self) -> u32 {
        MsgqRxHeader::read_ptr(io_project!(self.0, .cpuq.rx)) % MSGQ_NUM_PAGES
    }

    // Informs the GSP that it can send `elem_count` new pages into the message queue.
    fn advance_cpu_read_ptr(&mut self, elem_count: u32) {
        let rx = io_project!(self.0, .cpuq.rx);
        let rptr = MsgqRxHeader::read_ptr(rx).wrapping_add(elem_count) % MSGQ_NUM_PAGES;

        // Ensure read pointer is properly ordered.
        fence(Ordering::SeqCst);

        MsgqRxHeader::set_read_ptr(rx, rptr)
    }

    // Returns the index of the memory page the CPU can write the next command to.
    //
    // # Invariants
    //
    // - The returned value is within `0..MSGQ_NUM_PAGES`.
    fn cpu_write_ptr(&self) -> u32 {
        MsgqTxHeader::write_ptr(io_project!(self.0, .cpuq.tx)) % MSGQ_NUM_PAGES
    }

    // Informs the GSP that it can process `elem_count` new pages from the command queue.
    fn advance_cpu_write_ptr(&mut self, elem_count: u32) {
        let tx = io_project!(self.0, .cpuq.tx);
        let wptr = MsgqTxHeader::write_ptr(tx).wrapping_add(elem_count) % MSGQ_NUM_PAGES;
        MsgqTxHeader::set_write_ptr(tx, wptr);

        // Ensure all command data is visible before triggering the GSP read.
        fence(Ordering::SeqCst);
    }
}

impl DmaGspMem {
    /// Allocates a region on the command queue that is large enough to send a command of `size`
    /// bytes, waiting for space to become available based on the provided timeout.
    ///
    /// The type parameter `H` selects the message element header ([`GspMsgElement`] for RM RPC,
    /// [`GspGmcMsgElement`] for GMC).
    ///
    /// This returns a [`GspCommand`] ready to be written to by the caller.
    ///
    /// # Errors
    ///
    /// - `EMSGSIZE` if the command is larger than [`GSP_MSG_QUEUE_ELEMENT_SIZE_MAX`].
    /// - `ETIMEDOUT` if space does not become available within the timeout.
    /// - `EIO` if the command header is not properly aligned.
    fn allocate_command<H: FromBytes + AsBytes>(
        &mut self,
        bar: &Bar0,
        size: usize,
        timeout: Delta,
    ) -> Result<GspCommand<'_, H>> {
        if size_of::<H>() + size > GSP_MSG_QUEUE_ELEMENT_SIZE_MAX {
            return Err(EMSGSIZE);
        }
        read_poll_timeout(
            || Ok(Self::driver_write_area_size_v2(bar)),
            |available_bytes| *available_bytes >= size_of::<H>() + size,
            Delta::from_micros(1),
            timeout,
        )?;

        // Get the current writable area as an array of bytes.
        let (slice_1, slice_2) = {
            let (slice_1, slice_2) = self.driver_write_area_v2(bar);

            #[allow(clippy::incompatible_msrv)]
            (slice_1.as_flattened_mut(), slice_2.as_flattened_mut())
        };

        // Extract area for the message element header.
        let (header, slice_1) = H::from_bytes_mut_prefix(slice_1).ok_or(EIO)?;

        // Create the contents area.
        let (slice_1, slice_2) = if slice_1.len() > size {
            // Contents fits entirely in `slice_1`.
            (&mut slice_1[..size], &mut slice_2[0..0])
        } else {
            // Need all of `slice_1` and some of `slice_2`.
            let slice_2_len = size - slice_1.len();
            (slice_1, &mut slice_2[..slice_2_len])
        };

        Ok(GspCommand {
            header,
            contents: (slice_1, slice_2),
        })
    }
}

// Msgq v2 internals.
//
// Msgq v2 keeps the four ring pointers in BAR0 registers as monotonic `u32`
// counters that wrap on overflow. The slot index is `ptr % MSGQ_NUM_PAGES`
// only at the point of use, and the ring uses every slot (no "leave one
// empty" rule, since `head == tail` distinguishes empty from full).
//
// Register-to-role mapping for queue 0:
//
//     CPU TX write/doorbell:  NV_PGSP_QUEUE_HEAD
//     GSP TX read:            NV_PGSP_QUEUE_TAIL
//     GSP RX write:           NV_PGSP_MSGQ_HEAD
//     CPU RX read:            NV_PGSP_MSGQ_TAIL
//
// TODO: suspend/resume reset-recovery is not yet implemented. Detect by
// `(write - read) > MSGQ_NUM_PAGES`, which means the BAR0 registers were
// zeroed by a power-cycle while the in-memory ring still holds stale data.
// Cold boot starts with all four counters at zero and never trips this.
impl DmaGspMem {
    fn gsp_write_ptr_v2(bar: &Bar0) -> u32 {
        *bar.read(regs::NV_PGSP_MSGQ_HEAD).address()
    }

    fn gsp_read_ptr_v2(bar: &Bar0) -> u32 {
        *bar.read(regs::NV_PGSP_QUEUE_TAIL).address()
    }

    fn cpu_read_ptr_v2(bar: &Bar0) -> u32 {
        *bar.read(regs::NV_PGSP_MSGQ_TAIL).address()
    }

    fn cpu_write_ptr_v2(bar: &Bar0) -> u32 {
        *bar.read(regs::NV_PGSP_QUEUE_HEAD).address()
    }

    fn advance_cpu_read_ptr_v2(bar: &Bar0, count: u32) {
        let new_rptr = Self::cpu_read_ptr_v2(bar).wrapping_add(count);

        // Order all reads from the message data ahead of the read-pointer
        // update so the GSP cannot recycle the slots while we are still
        // looking at them.
        fence(Ordering::SeqCst);

        bar.write_reg(regs::NV_PGSP_MSGQ_TAIL::zeroed().with_address(new_rptr));
    }

    fn advance_cpu_write_ptr_v2(bar: &Bar0, count: u32) {
        let new_wptr = Self::cpu_write_ptr_v2(bar).wrapping_add(count);

        // Order all writes to the message data ahead of the write-pointer
        // update. Writing the head register doubles as the GSP doorbell.
        fence(Ordering::SeqCst);

        bar.write_reg(regs::NV_PGSP_QUEUE_HEAD::zeroed().with_address(new_wptr));
    }

    /// Returns the region of the CPU message queue that the driver is currently allowed to write
    /// to.
    ///
    /// As the message queue is a circular buffer, the region may be discontiguous in memory. In
    /// that case the second slice will have a non-zero length.
    fn driver_write_area_v2(
        &mut self,
        bar: &Bar0,
    ) -> (&mut [[u8; GSP_PAGE_SIZE]], &mut [[u8; GSP_PAGE_SIZE]]) {
        let raw_w = Self::cpu_write_ptr_v2(bar);
        let raw_r = Self::gsp_read_ptr_v2(bar);

        let used = raw_w.wrapping_sub(raw_r);
        let avail = MSGQ_NUM_PAGES.saturating_sub(used) as usize;
        let w_slot = num::u32_as_usize(raw_w % MSGQ_NUM_PAGES);

        // SAFETY:
        // - We will only access the driver-owned part of the shared memory.
        // - Per the safety statement of the function, no concurrent access will be performed.
        let gsp_mem = unsafe { &mut *self.0.as_mut() };
        let (before_w, after_w) = gsp_mem.cpuq.msgq.data.split_at_mut(w_slot);

        let in_after = avail.min(after_w.len());
        let in_before = avail - in_after;
        (&mut after_w[..in_after], &mut before_w[..in_before])
    }

    /// Returns the size, in bytes, of the region of the CPU message queue that the driver is
    /// currently allowed to write to.
    fn driver_write_area_size_v2(bar: &Bar0) -> usize {
        let used = Self::cpu_write_ptr_v2(bar).wrapping_sub(Self::gsp_read_ptr_v2(bar));
        let slots = MSGQ_NUM_PAGES.saturating_sub(used);
        num::u32_as_usize(slots) * GSP_PAGE_SIZE
    }

    /// Returns the region of the GSP message queue that the driver is currently allowed to read
    /// from.
    ///
    /// As the message queue is a circular buffer, the region may be discontiguous in memory. In
    /// that case the second slice will have a non-zero length.
    fn driver_read_area_v2(&self, bar: &Bar0) -> (&[[u8; GSP_PAGE_SIZE]], &[[u8; GSP_PAGE_SIZE]]) {
        let raw_w = Self::gsp_write_ptr_v2(bar);
        let raw_r = Self::cpu_read_ptr_v2(bar);

        let avail = num::u32_as_usize(raw_w.wrapping_sub(raw_r));
        let r_slot = num::u32_as_usize(raw_r % MSGQ_NUM_PAGES);

        // SAFETY:
        // - We will only access the driver-owned part of the shared memory.
        // - Per the safety statement of the function, no concurrent access will be performed.
        let gsp_mem = unsafe { &*self.0.as_ptr() };
        let data = &gsp_mem.gspq.msgq.data;
        let (before_r, after_r) = data.split_at(r_slot);

        let in_after = avail.min(after_r.len());
        let in_before = avail - in_after;
        (&after_r[..in_after], &before_r[..in_before])
    }
}

/// A command ready to be sent on the command queue.
///
/// The type parameter `H` is the message element header type ([`GspMsgElement`] for RM RPC,
/// [`GspGmcMsgElement`] for GMC).
///
/// This is the type returned by [`DmaGspMem::allocate_command`].
struct GspCommand<'a, H = GspMsgElement> {
    // Writable reference to the header of the command.
    header: &'a mut H,
    // Writable slices to the contents of the command. The second slice is zero unless the command
    // loops over the command queue.
    contents: (&'a mut [u8], &'a mut [u8]),
}

/// A message ready to be processed from the message queue.
///
/// This is the type returned by [`CmdqInner::wait_for_msg`].
struct GspMessage<'a> {
    // Reference to the header of the message.
    header: &'a GspMsgElement,
    // Slices to the contents of the message. The second slice is zero unless the message loops
    // over the message queue.
    contents: (&'a [u8], &'a [u8]),
}

/// A GMC message ready to be processed from the message queue.
///
/// This is the type returned by [`CmdqInner::wait_for_gmc_msg`].
struct GmcMessage<'a> {
    // Reference to the header of the message.
    header: &'a GspGmcMsgElement,
    // Slices to the contents of the message (after the GmcApiHeader). The second slice is zero
    // unless the message loops over the message queue.
    contents: (&'a [u8], &'a [u8]),
}

/// Response from a GMC API command.
///
/// Returned by [`Cmdq::send_gmc_and_receive`].
#[expect(dead_code)]
pub(crate) struct GmcResponse {
    /// The GMC command identifier from the response.
    pub(crate) command_id: u32,
    /// Response status (`NV_STATUS` code). Zero means success.
    pub(crate) status: u32,
    /// Response payload (copied from the message queue).
    pub(crate) payload: KVec<u8>,
}

/// GSP command queue.
///
/// Provides the ability to send commands and receive messages from the GSP using a shared memory
/// area.
#[pin_data]
pub(crate) struct Cmdq {
    /// Inner mutex-protected state.
    #[pin]
    inner: Mutex<CmdqInner>,
    /// DMA handle of the command queue's shared memory region.
    pub(super) dma_handle: DmaAddress,
}

impl Cmdq {
    /// Offset of the data after the PTEs.
    const POST_PTE_OFFSET: usize = core::mem::offset_of!(GspMem, cpuq);

    /// Offset of command queue ring buffer.
    pub(crate) const CMDQ_OFFSET: usize = core::mem::offset_of!(GspMem, cpuq)
        + core::mem::offset_of!(Msgq, msgq)
        - Self::POST_PTE_OFFSET;

    /// Offset of message queue ring buffer.
    pub(crate) const STATQ_OFFSET: usize = core::mem::offset_of!(GspMem, gspq)
        + core::mem::offset_of!(Msgq, msgq)
        - Self::POST_PTE_OFFSET;

    /// Number of page table entries for the GSP shared region.
    pub(crate) const NUM_PTES: usize = size_of::<GspMem>() >> GSP_PAGE_SHIFT;

    /// Default timeout for receiving a message from the GSP.
    pub(super) const RECEIVE_TIMEOUT: Delta = Delta::from_secs(5);

    /// Creates a new command queue for `dev`.
    pub(crate) fn new(dev: &device::Device<device::Bound>) -> impl PinInit<Self, Error> + '_ {
        pin_init_scope(move || {
            let gsp_mem = DmaGspMem::new(dev)?;

            Ok(try_pin_init!(Self {
                dma_handle: gsp_mem.0.dma_handle(),
                inner <- new_mutex!(CmdqInner {
                    dev: dev.into(),
                    gsp_mem,
                    seq: 0,
                    tx_async_seq: 0,
                    rx_event_seq: 0,
                }),
            }))
        })
    }

    /// Sends `command` to the GSP and waits for the reply.
    ///
    /// Messages with non-matching function codes are silently consumed until the expected reply
    /// arrives.
    ///
    /// The queue is locked for the entire send+receive cycle to ensure that no other command can
    /// be interleaved.
    ///
    /// # Errors
    ///
    /// - `ETIMEDOUT` if space does not become available to send the command, or if the reply is
    ///   not received within the timeout.
    /// - `EIO` if the variable payload requested by the command has not been entirely
    ///   written to by its [`CommandToGsp::init_variable_payload`] method.
    ///
    /// Error codes returned by the command and reply initializers are propagated as-is.
    #[expect(dead_code)]
    pub(crate) fn send_command<M>(&self, bar: &Bar0, command: M) -> Result<M::Reply>
    where
        M: CommandToGsp,
        M::Reply: MessageFromGsp,
        Error: From<M::InitError>,
        Error: From<<M::Reply as MessageFromGsp>::InitError>,
    {
        let mut inner = self.inner.lock();
        inner.send_command(bar, command)?;

        loop {
            match inner.receive_msg::<M::Reply>(bar, Self::RECEIVE_TIMEOUT) {
                Ok(reply) => break Ok(reply),
                Err(ERANGE) => continue,
                Err(e) => break Err(e),
            }
        }
    }

    /// Sends `command` to the GSP without waiting for a reply.
    ///
    /// # Errors
    ///
    /// - `ETIMEDOUT` if space does not become available within the timeout.
    /// - `EIO` if the variable payload requested by the command has not been entirely
    ///   written to by its [`CommandToGsp::init_variable_payload`] method.
    ///
    /// Error codes returned by the command initializers are propagated as-is.
    #[expect(dead_code)]
    pub(crate) fn send_command_no_wait<M>(&self, bar: &Bar0, command: M) -> Result
    where
        M: CommandToGsp<Reply = NoReply>,
        Error: From<M::InitError>,
    {
        self.inner.lock().send_command(bar, command)
    }

    /// Receive a message from the GSP.
    ///
    /// See [`CmdqInner::receive_msg`] for details.
    #[expect(dead_code)]
    pub(crate) fn receive_msg<M: MessageFromGsp>(&self, bar: &Bar0, timeout: Delta) -> Result<M>
    where
        // This allows all error types, including `Infallible`, to be used for `M::InitError`.
        Error: From<M::InitError>,
    {
        self.inner.lock().receive_msg(bar, timeout)
    }

    /// Receive the next message from GSP and dispatch it through a handler.
    ///
    /// See [`CmdqInner::receive_and_dispatch`] for details.
    #[expect(dead_code)]
    pub(crate) fn receive_and_dispatch<R>(
        &self,
        bar: &Bar0,
        timeout: Delta,
        handler: impl FnOnce(MsgFunction, &[u8], &[u8]) -> R,
    ) -> Result<R> {
        self.inner
            .lock()
            .receive_and_dispatch(bar, timeout, handler)
    }

    /// Receive the next GMC event from GSP and dispatch it through a handler.
    ///
    /// See [`CmdqInner::receive_gmc_and_dispatch`] for details.
    pub(crate) fn receive_gmc_and_dispatch<R>(
        &self,
        bar: &Bar0,
        timeout: Delta,
        handler: impl FnOnce(u32, u32, &[u8], &[u8]) -> R,
    ) -> Result<R> {
        self.inner
            .lock()
            .receive_gmc_and_dispatch(bar, timeout, handler)
    }

    /// Sends a GMC API command to the GSP without waiting for the response.
    ///
    /// # Errors
    ///
    /// - `EMSGSIZE` if the command exceeds the maximum queue element size.
    /// - `ETIMEDOUT` if space is not available before the timeout.
    pub(crate) fn send_gmc_no_wait(
        &self,
        bar: &Bar0,
        command_id: u32,
        payload: &[u8],
        max_response_size: u32,
    ) -> Result {
        self.inner
            .lock()
            .send_gmc(bar, command_id, payload, max_response_size)
    }

    /// Sends a GMC API command to the GSP and waits for the matching response.
    ///
    /// The queue is locked for the entire send+receive cycle. Messages whose
    /// command ID does not match `command_id` (after masking flags) are consumed
    /// and discarded — this prevents stale responses from earlier fire-and-forget
    /// commands from being misattributed.
    ///
    /// # Errors
    ///
    /// - `EMSGSIZE` if the command exceeds the maximum queue element size.
    /// - `ETIMEDOUT` if space is not available or the matching response is not
    ///   received in time.
    /// - `ENOMEM` if the response payload buffer cannot be allocated.
    pub(crate) fn send_gmc_and_receive(
        &self,
        bar: &Bar0,
        command_id: u32,
        payload: &[u8],
        max_response_size: u32,
    ) -> Result<GmcResponse> {
        let mut inner = self.inner.lock();
        inner.send_gmc(bar, command_id, payload, max_response_size)?;

        let expected = command_id & fw::GMCAPI_COMMAND_ID_MASK;
        loop {
            let resp = inner.receive_gmc(bar, Self::RECEIVE_TIMEOUT)?;
            if resp.command == expected {
                break Ok(resp);
            }
            dev_dbg!(
                &inner.dev,
                "GSP GMC: skipped non-matching response cmd={:#x} while waiting for {:#x}\n",
                resp.command, expected,
            );
        }
    }

    /// Send a GMC command and check the response status, ignoring the payload.
    ///
    /// Convenience wrapper around [`send_gmc_and_receive`](Self::send_gmc_and_receive)
    /// for commands where only the success/failure status matters.
    pub(crate) fn send_gmc_no_response(
        &self,
        bar: &Bar0,
        command_id: u32,
        payload: &[u8],
    ) -> Result {
        let resp = self.send_gmc_and_receive(bar, command_id, payload, 0)?;
        if resp.status != 0 {
            return Err(EIO);
        }
        Ok(())
    }

    /// Send a GMC command without waiting for a response (fire-and-forget).
    ///
    /// The GSP will process the command asynchronously and may later send a
    /// GMC event that can be consumed via [`wait_gmc_event`](Self::wait_gmc_event).
    pub(crate) fn send_gmc_fire_and_forget(
        &self,
        bar: &Bar0,
        command_id: u32,
        payload: &[u8],
    ) -> Result {
        let mut inner = self.inner.lock();
        inner.send_gmc(bar, command_id, payload, 0)
    }

    /// Wait for a GMC event matching `predicate`, polling the message queue.
    ///
    /// Drains incoming GMC messages until `predicate(command_id, payload)` returns
    /// `true` or `timeout` elapses. Non-matching messages are consumed and discarded.
    pub(crate) fn wait_gmc_event<F>(&self, bar: &Bar0, timeout: Delta, mut predicate: F) -> Result
    where
        F: FnMut(u32, &[u8]) -> bool,
    {
        let start = Instant::<Monotonic>::now();
        let inner = self.inner.lock();

        loop {
            let elapsed = Instant::<Monotonic>::now() - start;
            if elapsed > timeout {
                return Err(ETIMEDOUT);
            }

            let poll_step = Delta::from_millis(100);

            let msg = match inner.wait_for_gmc_msg(bar, poll_step) {
                Ok(msg) => msg,
                Err(e) if e == ETIMEDOUT => continue,
                Err(e) => return Err(e),
            };

            let command_id = msg.header.gmc.command_id;
            let (s1, s2) = msg.contents;
            let total_len = s1.len() + s2.len();
            let advance_pages =
                u32::try_from(msg.header.length().div_ceil(GSP_PAGE_SIZE)).unwrap_or(1);

            let matched = if s2.is_empty() {
                predicate(command_id, s1)
            } else {
                let mut buf = KVec::with_capacity(total_len, GFP_KERNEL)?;
                buf.extend_from_slice(s1, GFP_KERNEL)?;
                buf.extend_from_slice(s2, GFP_KERNEL)?;
                predicate(command_id, &buf)
            };

            DmaGspMem::advance_cpu_read_ptr_v2(bar, advance_pages);

            if matched {
                return Ok(());
            }
        }
    }
}

/// Inner mutex protected state of [`Cmdq`].
struct CmdqInner {
    /// Device this command queue belongs to.
    dev: ARef<device::Device>,
    /// RPC sequence counter, incremented for every send. Used as `rpc.sequence` for sync
    /// commands (set to 0 for async commands).
    seq: u32,
    /// Async (fire-and-forget) send sequence number, for debug logging.
    tx_async_seq: u32,
    /// Async event receive sequence number, for debug logging. GSP does not populate
    /// rpc.sequence for async events today, so the driver counts them itself.
    rx_event_seq: u32,
    /// Memory area shared with the GSP for communicating commands and messages.
    gsp_mem: DmaGspMem,
}

impl CmdqInner {
    /// Timeout for waiting for space on the command queue.
    const ALLOCATE_TIMEOUT: Delta = Delta::from_secs(1);

    /// Sends `command` to the GSP, without splitting it.
    ///
    /// # Errors
    ///
    /// - `EMSGSIZE` if the command exceeds the maximum queue element size.
    /// - `ETIMEDOUT` if space does not become available within the timeout.
    /// - `EIO` if the variable payload requested by the command has not been entirely
    ///   written to by its [`CommandToGsp::init_variable_payload`] method.
    ///
    /// Error codes returned by the command initializers are propagated as-is.
    fn send_single_command<M>(&mut self, bar: &Bar0, command: M) -> Result
    where
        M: CommandToGsp,
        // This allows all error types, including `Infallible`, to be used for `M::InitError`.
        Error: From<M::InitError>,
    {
        let size_in_bytes = command.size();
        let dst = self
            .gsp_mem
            .allocate_command(bar, size_in_bytes, Self::ALLOCATE_TIMEOUT)?;

        // Extract area for the command itself. The GSP message header and the command header
        // together are guaranteed to fit entirely into a single page, so it's ok to only look
        // at `dst.contents.0` here.
        let (cmd, payload_1) = M::Command::from_bytes_mut_prefix(dst.contents.0).ok_or(EIO)?;

        // rpc.sequence is 0 for async (fire-and-forget) commands, or the
        // sequence counter for command/response pairs, matching Open RM behavior.
        let rpc_seq = if M::IS_ASYNC { 0 } else { self.seq };

        // Fill the header and command in-place.
        let msg_element = GspMsgElement::init(rpc_seq, size_in_bytes, M::FUNCTION);
        // SAFETY: `msg_header` and `cmd` are valid references, and not touched if the initializer
        // fails.
        unsafe {
            msg_element.__init(core::ptr::from_mut(dst.header))?;
            command.init().__init(core::ptr::from_mut(cmd))?;
        }

        // Fill the variable-length payload, which may be empty.
        let mut sbuffer = SBufferIter::new_writer([&mut payload_1[..], &mut dst.contents.1[..]]);
        command.init_variable_payload(&mut sbuffer)?;

        if !sbuffer.is_empty() {
            return Err(EIO);
        }
        drop(sbuffer);

        if M::IS_ASYNC {
            dev_dbg!(
                &self.dev,
                "GSP RPC: async send: seq# {}, function={:?}, length=0x{:x}\n",
                self.tx_async_seq,
                M::FUNCTION,
                dst.header.length(),
            );
            self.tx_async_seq += 1;
        } else {
            dev_dbg!(
                &self.dev,
                "GSP RPC: send: seq# {}, function={:?}, length=0x{:x}\n",
                self.seq,
                M::FUNCTION,
                dst.header.length(),
            );
        }

        // All set - update the write pointer. The pointer write doubles as the GSP doorbell.
        let elem_count = dst.header.element_count();
        self.seq += 1;
        DmaGspMem::advance_cpu_write_ptr_v2(bar, elem_count);

        Ok(())
    }

    /// Sends `command` to the GSP.
    ///
    /// The command may be split into multiple messages if it is large.
    ///
    /// # Errors
    ///
    /// - `ETIMEDOUT` if space does not become available within the timeout.
    /// - `EIO` if the variable payload requested by the command has not been entirely
    ///   written to by its [`CommandToGsp::init_variable_payload`] method.
    ///
    /// Error codes returned by the command initializers are propagated as-is.
    fn send_command<M>(&mut self, bar: &Bar0, command: M) -> Result
    where
        M: CommandToGsp,
        Error: From<M::InitError>,
    {
        match SplitState::new(command)? {
            SplitState::Single(command) => self.send_single_command(bar, command),
            SplitState::Split(command, mut continuations) => {
                self.send_single_command(bar, command)?;

                while let Some(continuation) = continuations.next() {
                    // Turbofish needed because the compiler cannot infer M here.
                    self.send_single_command::<ContinuationRecord<'_>>(bar, continuation)?;
                }

                Ok(())
            }
        }
    }

    /// Sends a GMC API command to the GSP.
    ///
    /// `command_id` is the GMC command identifier (from `GMCAPI_COMMANDS`).
    /// `payload` is the command-specific data following the [`GmcApiHeader`].
    /// `max_response_size` is the maximum expected response payload size.
    ///
    /// [`GmcApiHeader`]: super::fw::GmcApiHeader
    ///
    /// # Errors
    ///
    /// - `EMSGSIZE` if the command exceeds the maximum queue element size.
    /// - `ETIMEDOUT` if space does not become available within the timeout.
    fn send_gmc(
        &mut self,
        bar: &Bar0,
        command_id: u32,
        payload: &[u8],
        max_response_size: u32,
    ) -> Result {
        let dst = self.gsp_mem.allocate_command::<GspGmcMsgElement>(
            bar,
            payload.len(),
            Self::ALLOCATE_TIMEOUT,
        )?;

        let msg_element = GspGmcMsgElement::init(
            command_id,
            u64::from(self.seq),
            payload.len(),
            max_response_size,
        );
        // SAFETY: `dst.header` points to a valid, writable `GspGmcMsgElement` region.
        unsafe {
            msg_element.__init(core::ptr::from_mut(dst.header))?;
        }

        // Copy the payload into the command buffer.
        let mut sbuffer =
            SBufferIter::new_writer([&mut dst.contents.0[..], &mut dst.contents.1[..]]);
        sbuffer.write_all(payload)?;
        drop(sbuffer);

        dev_dbg!(
            &self.dev,
            "GSP GMC: send: seq# {}, command_id=0x{:x}, length=0x{:x}\n",
            self.seq,
            command_id,
            dst.header.length(),
        );

        let elem_count = dst.header.element_count();
        self.seq += 1;
        DmaGspMem::advance_cpu_write_ptr_v2(bar, elem_count);

        Ok(())
    }

    /// Wait for a message to become available on the message queue.
    ///
    /// This works purely at the transport layer and does not interpret or validate the message
    /// beyond the advertised length in its [`GspMsgElement`].
    ///
    /// This method returns:
    ///
    /// - A reference to the [`GspMsgElement`] of the message,
    /// - Two byte slices with the contents of the message. The second slice is empty unless the
    ///   message loops across the message queue.
    ///
    /// # Errors
    ///
    /// - `ETIMEDOUT` if `timeout` has elapsed before any message becomes available.
    /// - `EIO` if there was some inconsistency (e.g. message shorter than advertised) on the
    ///   message queue.
    ///
    /// Error codes returned by the message constructor are propagated as-is.
    fn wait_for_msg(&self, bar: &Bar0, timeout: Delta) -> Result<GspMessage<'_>> {
        // Wait for a message to arrive from the GSP.
        let (slice_1, slice_2) = read_poll_timeout(
            || Ok(self.gsp_mem.driver_read_area_v2(bar)),
            |driver_area| !driver_area.0.is_empty(),
            Delta::from_millis(1),
            timeout,
        )
        .map(|(slice_1, slice_2)| {
            #[allow(clippy::incompatible_msrv)]
            (slice_1.as_flattened(), slice_2.as_flattened())
        })?;

        // Extract the `GspMsgElement`.
        let (header, slice_1) = GspMsgElement::from_bytes_prefix(slice_1).ok_or(EIO)?;

        let payload_length = header.payload_length();

        // Check that the driver read area is large enough for the message.
        if slice_1.len() + slice_2.len() < payload_length {
            return Err(EIO);
        }

        // Cut the message slices down to the actual length of the message.
        let (slice_1, slice_2) = if slice_1.len() > payload_length {
            // PANIC: we checked above that `slice_1` is at least as long as `payload_length`.
            (slice_1.split_at(payload_length).0, &slice_2[0..0])
        } else {
            (
                slice_1,
                // PANIC: we checked above that `slice_1.len() + slice_2.len()` is at least as
                // large as `payload_length`.
                slice_2.split_at(payload_length - slice_1.len()).0,
            )
        };

        if !header.has_valid_magic() {
            dev_err!(
                &self.dev,
                "GSP RPC: receive: Call {} - bad MCTP magic\n",
                header.sequence()
            );
            return Err(EIO);
        }

        Ok(GspMessage {
            header,
            contents: (slice_1, slice_2),
        })
    }

    /// Receive a message from the GSP.
    ///
    /// The expected message type is specified using the `M` generic parameter. If the pending
    /// message has a different function code, `ERANGE` is returned and the message is consumed.
    ///
    /// The read pointer is always advanced past the message, regardless of whether it matched.
    ///
    /// # Errors
    ///
    /// - `ETIMEDOUT` if `timeout` has elapsed before any message becomes available.
    /// - `EIO` if there was some inconsistency (e.g. message shorter than advertised) on the
    ///   message queue.
    /// - `EINVAL` if the function code of the message was not recognized.
    /// - `ERANGE` if the message had a recognized but non-matching function code.
    ///
    /// Error codes returned by [`MessageFromGsp::read`] are propagated as-is.
    fn receive_msg<M: MessageFromGsp>(&mut self, bar: &Bar0, timeout: Delta) -> Result<M>
    where
        // This allows all error types, including `Infallible`, to be used for `M::InitError`.
        Error: From<M::InitError>,
    {
        let message = self.wait_for_msg(bar, timeout)?;
        let function = message.header.function().map_err(|_| EINVAL)?;
        let is_event = function.is_event();

        if is_event {
            dev_dbg!(
                &self.dev,
                "GSP RPC: async received: seq# {}, function={:?}, length=0x{:x}\n",
                self.rx_event_seq,
                function,
                message.header.length(),
            );
        } else {
            dev_dbg!(
                &self.dev,
                "GSP RPC: response received: seq# {}, function={:?}, length=0x{:x}\n",
                message.header.sequence(),
                function,
                message.header.length(),
            );
        }

        // Extract the message. Store the result as we want to advance the read pointer even in
        // case of failure.
        let result = if function == M::FUNCTION {
            let (cmd, contents_1) = M::Message::from_bytes_prefix(message.contents.0).ok_or(EIO)?;
            let mut sbuffer = SBufferIter::new_reader([contents_1, message.contents.1]);

            M::read(cmd, &mut sbuffer)
                .map_err(|e| e.into())
                .inspect(|_| {
                    if !sbuffer.is_empty() {
                        dev_warn!(
                            &self.dev,
                            "GSP message {:?} has unprocessed data\n",
                            function
                        );
                    }
                })
        } else {
            Err(ERANGE)
        };

        // Advance the read pointer past this message.
        DmaGspMem::advance_cpu_read_ptr_v2(
            bar,
            u32::try_from(message.header.length().div_ceil(GSP_PAGE_SIZE))?,
        );

        // Deferred past message consumption to satisfy the borrow checker: message
        // holds a reference into self.gsp_mem, so we can't mutate self until it's dropped.
        if is_event {
            self.rx_event_seq += 1;
        }

        result
    }

    /// Receive the next message from GSP and dispatch it through a handler.
    ///
    /// The handler receives the [`MsgFunction`] and the raw payload slices (two slices because
    /// the circular buffer may wrap). The message is consumed from the queue after the handler
    /// returns, regardless of the handler's result.
    ///
    /// This is the dispatch-based counterpart to [`CmdqInner::receive_msg`]. Where `receive_msg`
    /// expects a specific message type, this method lets the caller handle multiple event types
    /// in a single receive loop (e.g. waiting for `INIT_DONE` while handling `LOAD_EXEC` events).
    fn receive_and_dispatch<R>(
        &mut self,
        bar: &Bar0,
        timeout: Delta,
        handler: impl FnOnce(MsgFunction, &[u8], &[u8]) -> R,
    ) -> Result<R> {
        let message = self.wait_for_msg(bar, timeout)?;
        let function = message.header.function().map_err(|_| EINVAL)?;
        let is_event = function.is_event();

        if is_event {
            dev_dbg!(
                &self.dev,
                "GSP RPC: async received: seq# {}, function={:?}, length=0x{:x}\n",
                self.rx_event_seq,
                function,
                message.header.length(),
            );
        } else {
            dev_dbg!(
                &self.dev,
                "GSP RPC: response received: seq# {}, function={:?}, length=0x{:x}\n",
                message.header.sequence(),
                function,
                message.header.length(),
            );
        }

        let result = handler(function, message.contents.0, message.contents.1);

        DmaGspMem::advance_cpu_read_ptr_v2(
            bar,
            u32::try_from(message.header.length().div_ceil(GSP_PAGE_SIZE))?,
        );

        Ok(result)
    }

    /// Wait for a GMC message to become available on the message queue.
    ///
    /// This is the GMC counterpart to [`CmdqInner::wait_for_msg`]. It parses a
    /// [`GspGmcMsgElement`] instead of a [`GspMsgElement`].
    fn wait_for_gmc_msg(&self, bar: &Bar0, timeout: Delta) -> Result<GmcMessage<'_>> {
        let (slice_1, slice_2) = read_poll_timeout(
            || Ok(self.gsp_mem.driver_read_area_v2(bar)),
            |driver_area| !driver_area.0.is_empty(),
            Delta::from_millis(1),
            timeout,
        )
        .map(|(slice_1, slice_2)| {
            #[allow(clippy::incompatible_msrv)]
            (slice_1.as_flattened(), slice_2.as_flattened())
        })?;

        let (header, slice_1) = GspGmcMsgElement::from_bytes_prefix(slice_1).ok_or(EIO)?;

        let payload_length = header.payload_length();

        if slice_1.len() + slice_2.len() < payload_length {
            return Err(EIO);
        }

        let (slice_1, slice_2) = if slice_1.len() > payload_length {
            (slice_1.split_at(payload_length).0, &slice_2[0..0])
        } else {
            (slice_1, slice_2.split_at(payload_length - slice_1.len()).0)
        };

        if !header.has_valid_magic() {
            dev_err!(
                &self.dev,
                "GSP GMC: receive: seq {} - bad MCTP magic\n",
                header.gmc.sequence
            );
            return Err(EIO);
        }

        Ok(GmcMessage {
            header,
            contents: (slice_1, slice_2),
        })
    }

    /// Receive a GMC response from the GSP.
    ///
    /// Copies the response payload out of the message queue and advances the read pointer.
    ///
    /// # Errors
    ///
    /// - `ETIMEDOUT` if `timeout` elapses before a message arrives.
    /// - `EIO` if the message queue is inconsistent or the MCTP magic is invalid.
    /// - `ENOMEM` if the payload buffer cannot be allocated.
    fn receive_gmc(&mut self, bar: &Bar0, timeout: Delta) -> Result<GmcResponse> {
        let message = self.wait_for_gmc_msg(bar, timeout)?;

        dev_dbg!(
            &self.dev,
            "GSP GMC: response received: seq {}, command_id=0x{:x}, status=0x{:x}, length=0x{:x}\n",
            message.header.gmc.sequence,
            message.header.gmc.command_id,
            message.header.gmc.size_or_status,
            message.header.length(),
        );

        let total_len = message.contents.0.len() + message.contents.1.len();
        let mut payload = KVec::with_capacity(total_len, GFP_KERNEL)?;
        payload.extend_from_slice(message.contents.0, GFP_KERNEL)?;
        payload.extend_from_slice(message.contents.1, GFP_KERNEL)?;

        let response = GmcResponse {
            command_id: message.header.gmc.command_id,
            status: message.header.gmc.size_or_status,
            payload,
        };

        DmaGspMem::advance_cpu_read_ptr_v2(
            bar,
            u32::try_from(message.header.length().div_ceil(GSP_PAGE_SIZE))?,
        );

        Ok(response)
    }

    /// Receive the next GMC event from GSP and dispatch it through a handler.
    ///
    /// The handler receives the GMC command id and the raw payload slices that follow the
    /// `GmcApiHeader` (two slices because the circular buffer may wrap). The message is
    /// consumed from the queue after the handler returns, regardless of the handler's result.
    ///
    /// This is the GMC counterpart to [`CmdqInner::receive_and_dispatch`]. Where
    /// `receive_and_dispatch` handles RPC-style messages keyed by [`MsgFunction`], this method
    /// handles GMC events keyed by command id, which is the form r000 firmware uses for boot
    /// events.
    fn receive_gmc_and_dispatch<R>(
        &mut self,
        bar: &Bar0,
        timeout: Delta,
        handler: impl FnOnce(u32, u32, &[u8], &[u8]) -> R,
    ) -> Result<R> {
        let message = self.wait_for_gmc_msg(bar, timeout)?;
        let command_id = message.header.gmc.command_id;
        let status = message.header.gmc.size_or_status;

        dev_dbg!(
            &self.dev,
            "GSP GMC: event received: seq {}, command_id=0x{:x}, status=0x{:x}, length=0x{:x}\n",
            message.header.gmc.sequence,
            command_id,
            status,
            message.header.length(),
        );

        let result = handler(command_id, status, message.contents.0, message.contents.1);

        DmaGspMem::advance_cpu_read_ptr_v2(
            bar,
            u32::try_from(message.header.length().div_ceil(GSP_PAGE_SIZE))?,
        );

        Ok(result)
    }
}
