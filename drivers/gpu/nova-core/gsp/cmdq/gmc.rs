/// Trait implemented by types representing a GMC command to send to the GSP.
///
/// The main purpose of this trait is to provide [`Cmdq`] with the information it needs to send
/// a given command.
///
/// [`CommandToGsp::init`] in particular is responsible for initializing the command directly
/// into the space reserved for it in the command queue buffer.
///
/// Some commands may be followed by a variable-length payload. For these, the
/// [`CommandToGsp::variable_payload_len`] and [`CommandToGsp::init_variable_payload`] need to be
/// defined as well.
pub(crate) trait CommandToGsp {
    /// Id identifying this command to the GSP.
    const COMMAND: GmcCommandId;

    /// Type generated by [`CommandToGsp::init`], to be written into the command queue buffer right
    /// after the GMC API header.
    type Command: FromBytes + AsBytes;

    /// Type of the reply expected from the GSP, or [`NoReply`] for commands that don't have a
    /// reply.
    type Reply;

    /// Response payload capacity in bytes. Zero permits a status-only response; whether the
    /// command sends a reply is determined by its protocol and [`Self::Reply`].
    const MAX_REPLY_SIZE: u32;

    /// Error type returned by [`CommandToGsp::init`].
    type InitError;

    /// In-place command initializer responsible for filling the command in the command queue
    /// buffer.
    fn init(&self) -> impl Init<Self::Command, Self::InitError>;

    /// Size of the variable-length payload following the command structure generated by
    /// [`CommandToGsp::init`].
    ///
    /// Most commands don't have a variable-length payload, so this is zero by default.
    fn variable_payload_len(&self) -> usize {
        0
    }

    /// Method initializing the variable-length payload.
    ///
    /// The command buffer is circular, which means that we may need to jump back to its beginning
    /// while in the middle of a command. For this reason, the variable-length payload is
    /// initialized using a [`SBufferIter`].
    ///
    /// This method will receive a buffer of the length returned by
    /// [`CommandToGsp::variable_payload_len`], and must write every single byte of it. Leaving
    /// unwritten space will lead to an error.
    ///
    /// Most commands don't have a variable-length payload, so this does nothing by default.
    fn init_variable_payload(
        &self,
        _dst: &mut SBufferIter<core::array::IntoIter<&mut [u8], 2>>,
    ) -> Result {
        Ok(())
    }

    /// Total size of the command (including its variable-length payload) without the GMC API
    /// header, i.e. the payload size advertised by that header.
    fn size(&self) -> usize {
        size_of::<Self::Command>() + self.variable_payload_len()
    }
}

/// Wrapper type for sending a GMC command as a command queue element.
struct GmcCommandElement<C>(C);

impl<C> CommandElement for GmcCommandElement<C>
where
    C: CommandToGsp,
    Error: From<C::InitError>,
{
    const NVDM_TYPE: NvdmType = NvdmType::GmcApi;

    fn size(&self) -> usize {
        size_of::<GmcApiHeader>() + self.0.size()
    }

    fn write(&self, dev: &device::Device, seq: u32, dst: &mut GspCommand<'_>) -> Result {
        let command = &self.0;
        let payload_size = command.size();
        // Extract the areas for the GMC API header and the command itself. The queue element
        // header, the GMC API header and the command header together are guaranteed to fit
        // entirely into a single page, so it's ok to only look at `dst.contents.0` here.
        let (header, contents) = GmcApiHeader::from_bytes_mut_prefix(dst.contents.0).ok_or(EIO)?;
        let (cmd, payload_1) = C::Command::from_bytes_mut_prefix(contents).ok_or(EIO)?;
        let header_init =
            GmcApiHeader::init(C::COMMAND, u64::from(seq), payload_size, C::MAX_REPLY_SIZE);
        // SAFETY: `header` is a valid reference, and is not touched if the initializer fails.
        unsafe {
            pin_init::raw_try_init(core::ptr::from_mut(header), header_init)?;
        }
        // SAFETY: `cmd` is a valid reference, and is not touched if the initializer fails.
        unsafe {
            pin_init::raw_try_init(core::ptr::from_mut(cmd), command.init())?;
        }

        // Fill the variable-length payload, which may be empty.
        let mut sbuffer = SBufferIter::new_writer([&mut payload_1[..], &mut dst.contents.1[..]]);
        command.init_variable_payload(&mut sbuffer)?;

        if !sbuffer.is_empty() {
            return Err(EIO);
        }

        dev_dbg!(
            dev,
            "GSP GMC: send: seq# {}, command={}, length=0x{:x}\n",
            seq,
            GmcCommand::from(C::COMMAND),
            payload_size,
        );

        Ok(())
    }
}

/// Trait representing GMC messages received from the GSP.
///
/// These can be either replies to sent commands that expect a reply, or an event not bound to any
/// command.
pub(crate) trait MessageFromGsp: Sized {
    /// Id of the command this is the reply to.
    const COMMAND: GmcCommandId;

    /// Error type returned by [`MessageFromGsp::read`].
    type InitError;

    /// Method reading the reply from the payload of the message and returning it.
    fn read(
        payload: &mut SBufferIter<core::array::IntoIter<&[u8], 2>>,
    ) -> Result<Self, Self::InitError>;
}

/// A GMC message ready to be processed from the message queue.
pub(crate) struct GmcMessage<'a> {
    // Reference to the GMC API header of the message.
    header: &'a GmcApiHeader,
    // Slices to the payload of the message. The second slice is empty unless the message loops
    // over the message queue.
    contents: (&'a [u8], &'a [u8]),
}

impl<'a> GmcMessage<'a> {
    /// Validate the GMC layer of `element` and returns its GMC API header and its contents, the
    /// GMC payload.
    ///
    /// # Errors
    ///
    /// - `EIO` if the element is shorter than the GMC API header, or if the payload length that
    ///   the GMC API header advertises differs from the one that the queue element header does.
    pub(super) fn parse(dev: &device::Device, element: GspMessage<'a>) -> Result<GmcMessage<'a>> {
        let GspMessage {
            contents: (slice_1, slice_2),
            ..
        } = element;

        // The queue element header and the GMC API header together are guaranteed to fit entirely
        // into a single page, so it's ok to only look at `slice_1` here.
        let (gmc_header, slice_1) = GmcApiHeader::from_bytes_prefix(slice_1).ok_or(EIO)?;
        let payload_size = gmc_header.payload_size();
        let kind = if gmc_header.command().is_response() {
            "response"
        } else {
            "event"
        };

        dev_dbg!(
            dev,
            "GSP GMC: {}: seq# {}, command={}, length=0x{:x}\n",
            kind,
            gmc_header.sequence_number(),
            GmcCommand::from(gmc_header.command()),
            payload_size,
        );

        // GSP-RM writes both lengths from the same payload, so a difference means that one of the
        // two headers is corrupt, and the driver cannot know which.
        let contents_len = slice_1.len() + slice_2.len();
        if contents_len != payload_size {
            dev_err!(
                dev,
                "GSP GMC: payload is {} bytes in the queue element header but {} in the GMC API header\n",
                contents_len,
                payload_size,
            );
            return Err(EIO);
        }

        Ok(GmcMessage {
            header: gmc_header,
            contents: (slice_1, slice_2),
        })
    }

    /// Returns the GMC API header of the message.
    pub(crate) fn header(&self) -> &'a GmcApiHeader {
        self.header
    }

    /// Returns the payload of the message.
    ///
    /// The second slice is empty unless the message loops over the message queue.
    pub(crate) fn payload(&self) -> (&'a [u8], &'a [u8]) {
        self.contents
    }

    /// Returns the status code of this message if it is the reply to `command` sent with sequence
    /// number `seq`, `None` otherwise.
    fn is_reply_to(&self, command: GmcCommandId, seq: u32) -> Option<u32> {
        // CAST: `GmcCommandId` is `repr(u32)`, so this cast is lossless.
        if self.header.is_response_to(command as u32, seq) {
            self.header.status()
        } else {
            None
        }
    }

    /// Logs an event, meaning a message that no caller was waiting for.
    ///
    /// A reply that nobody claimed (e.g. one that arrived after its request timed out) and an
    /// unknown command id are logged at warning level. Other events are not logged.
    pub(super) fn log(&self, dev: &device::Device) {
        let command = self.header.command();
        let seq = self.header.sequence_number();
        let kind = if command.is_response() {
            "response"
        } else {
            "event"
        };

        match command.id() {
            Ok(id) if command.is_response() => {
                dev_warn!(
                    dev,
                    "unclaimed GSP GMC response to {} (seq# {})\n",
                    GmcCommand::from(id),
                    seq
                );
            }
            // Nothing to do for the remaining known command ids.
            Ok(_) => {}
            Err(_) => {
                dev_warn!(
                    dev,
                    "unhandled GSP GMC {}: command={} (seq# {})\n",
                    kind,
                    GmcCommand::from(command),
                    seq
                );
            }
        }
    }
}

/// Response from a GMC API command.
pub(crate) struct GmcResponse {
    /// Response status (`NV_STATUS` code). Zero means success.
    #[expect(dead_code)]
    pub(crate) status: u32,
    /// Response payload copied out of the message queue.
    #[expect(dead_code)]
    pub(crate) payload: KVec<u8>,
}

/// A byte payload sent with a runtime-selected GMC command ID.
struct RawGmcCommand<'a> {
    command_id: u32,
    payload: &'a [u8],
    max_response_size: u32,
}

impl CommandElement for RawGmcCommand<'_> {
    const NVDM_TYPE: NvdmType = NvdmType::GmcApi;

    fn size(&self) -> usize {
        size_of::<GmcApiHeader>() + self.payload.len()
    }

    fn write(&self, dev: &device::Device, seq: u32, dst: &mut GspCommand<'_>) -> Result {
        let (header, payload_0) = GmcApiHeader::from_bytes_mut_prefix(dst.contents.0).ok_or(EIO)?;
        let init = GmcApiHeader::init_raw(
            self.command_id,
            u64::from(seq),
            self.payload.len(),
            self.max_response_size,
        );
        // SAFETY: `header` is valid and is not touched if initialization fails.
        unsafe { pin_init::raw_try_init(core::ptr::from_mut(header), init)? };
        SBufferIter::new_writer([payload_0, &mut dst.contents.1[..]]).write_all(self.payload)?;
        dev_dbg!(
            dev,
            "GSP GMC: send: seq# {}, command={}, length=0x{:x}\n",
            seq,
            GmcCommand(self.command_id & 0x00ff_ffff),
            self.payload.len(),
        );
        Ok(())
    }
}

impl Cmdq<'_> {
    /// Sends a GMC API command and waits for its matching response.
    ///
    /// Uses [`Self::RECEIVE_TIMEOUT`] as the receive timeout. Firmware rejection is returned in
    /// [`GmcResponse::status`], not as an error.
    ///
    /// See [`Self::send_gmc_and_receive_timeout`] for message consumption and locking behavior.
    ///
    /// # Errors
    ///
    /// Returns the same errors as [`Self::send_gmc_and_receive_timeout`].
    #[expect(dead_code)]
    pub(crate) fn send_gmc_and_receive(
        &self,
        command_id: u32,
        payload: &[u8],
        max_response_size: u32,
    ) -> Result<GmcResponse> {
        self.send_gmc_and_receive_timeout(
            command_id,
            payload,
            max_response_size,
            Self::RECEIVE_TIMEOUT,
        )
    }

    /// Sends a GMC API command and waits up to `timeout` for its matching response.
    ///
    /// Matches both the command ID and the request's sequence number. A nonzero firmware status
    /// is returned in [`GmcResponse::status`]; the caller decides how to handle rejection.
    /// `max_response_size` advertises the response payload capacity in bytes, so zero still
    /// permits a status-only response.
    ///
    /// Unmatched GMC responses and events are debug-logged and consumed. Interleaved RPC messages
    /// are logged as events and consumed. The matching response is also consumed if copying its
    /// payload fails.
    ///
    /// The queue stays locked from sending through receiving. One receive deadline starts after
    /// sending and is not extended by other messages. It does not bound waiting for the mutex or
    /// for space to send the request.
    ///
    /// # Errors
    ///
    /// - `EMSGSIZE` if the request exceeds the command queue's maximum element size.
    /// - `ETIMEDOUT` if space does not become available to send the request, or if the matching
    ///   response does not arrive before the receive deadline.
    /// - `EIO` if the command queue slot cannot hold the request headers, the receive queue is
    ///   stalled by an invalid element, or a received element fails framing validation.
    /// - `ENOMEM` if the response payload cannot be allocated.
    ///
    /// Errors from initializing the request headers are propagated as-is.
    pub(crate) fn send_gmc_and_receive_timeout(
        &self,
        command_id: u32,
        payload: &[u8],
        max_response_size: u32,
        timeout: Delta,
    ) -> Result<GmcResponse> {
        let mut inner = self.inner.lock();
        let expected_sequence = inner.send_command_element(RawGmcCommand {
            command_id,
            payload,
            max_response_size,
        })?;
        let dev = inner.dev;

        let deadline = Instant::<Monotonic>::now() + timeout;
        inner.await_msg_with_deadline(deadline, |message| {
            let GspParsedMessage::Gmc(message) = message else {
                message.log(dev);
                return Ok(None);
            };
            let header = message.header();
            let (payload_0, payload_1) = message.payload();
            if !header.is_response_to(command_id, expected_sequence) {
                let kind = if header.command().is_response() {
                    "response"
                } else {
                    "event"
                };
                dev_dbg!(
                    dev,
                    "GSP GMC: skip {} seq {} cmd {:#x}; want response seq {} cmd {:#x}\n",
                    kind,
                    header.sequence(),
                    GmcCommand::from(header.command()).0,
                    expected_sequence,
                    command_id,
                );
                return Ok(None);
            }

            // Each byte slice is at most `isize::MAX` bytes, so their sum fits in `usize`.
            let mut payload = KVec::with_capacity(payload_0.len() + payload_1.len(), GFP_KERNEL)?;
            payload.extend_from_slice(payload_0, GFP_KERNEL)?;
            payload.extend_from_slice(payload_1, GFP_KERNEL)?;
            Ok(Some(GmcResponse {
                status: header.status().ok_or(EIO)?,
                payload,
            }))
        })
    }

    /// Sends an asynchronous GMC command and waits atomically for its event.
    ///
    /// The command queue remains locked from the send through the matching
    /// event, preventing another transaction from consuming its completion.
    /// GMC events are passed to `predicate`, then to `handler` if the predicate returns false.
    /// GMC responses are debug-logged and consumed without invoking either callback. Interleaved
    /// RPC messages are logged as events and consumed.
    ///
    /// One receive deadline starts after sending and is not extended by other messages. It does
    /// not bound waiting for the mutex or for space to send the request.
    ///
    /// Both callbacks run with the queue locked and must not reenter this queue or reset it.
    /// Their second argument is the raw `max_resp_or_status` word of the event header.
    ///
    /// # Errors
    ///
    /// - `EMSGSIZE` if the request exceeds the command queue's maximum element size.
    /// - `ETIMEDOUT` if space does not become available to send the request, or if no event
    ///   satisfies `predicate` before the receive deadline.
    /// - `EIO` if the command queue slot cannot hold the request headers, the receive queue is
    ///   stalled by an invalid element, or a received element fails framing validation.
    ///
    /// Errors from initializing the request headers and from either callback are propagated
    /// as-is. The current valid element is consumed before a callback error is returned.
    #[expect(dead_code)]
    pub(crate) fn send_gmc_and_wait_event(
        &self,
        command_id: u32,
        payload: &[u8],
        timeout: Delta,
        mut predicate: impl FnMut(u32, u32, u64, &[u8], &[u8]) -> Result<bool>,
        mut handler: impl FnMut(u32, u32, u64, &[u8], &[u8]) -> Result,
    ) -> Result {
        let mut inner = self.inner.lock();
        inner.send_command_element(RawGmcCommand {
            command_id,
            payload,
            max_response_size: 0,
        })?;
        let dev = inner.dev;
        let deadline = Instant::<Monotonic>::now() + timeout;

        inner.await_msg_with_deadline(deadline, |message| {
            let GspParsedMessage::Gmc(message) = message else {
                message.log(dev);
                return Ok(None);
            };
            let header = message.header();
            let (payload_0, payload_1) = message.payload();
            if header.command().is_response() {
                return Ok(None);
            }

            let command = GmcCommand::from(header.command()).0;
            let max_resp_or_status = header.raw_status_word();
            let sequence = header.sequence();
            if predicate(command, max_resp_or_status, sequence, payload_0, payload_1)? {
                return Ok(Some(()));
            }

            handler(command, max_resp_or_status, sequence, payload_0, payload_1)?;
            Ok(None)
        })
    }

    /// Sends `command` to the GSP and waits for the reply.
    ///
    /// GMC events that arrive before the reply are passed to `on_event`, and RPC messages are
    /// logged and consumed. The boot sequence relies on this to handle the load-and-execute
    /// events that GSP-RM raises before it answers `GSP_INIT`.
    ///
    /// The queue is locked for the entire send+receive cycle, including the calls to `on_event`,
    /// to ensure that no other command can be interleaved. `on_event` must thus not use the queue.
    ///
    /// # Errors
    ///
    /// - `EMSGSIZE` if the command does not fit in a single command queue element.
    /// - `ETIMEDOUT` if space does not become available to send the command, or if the reply does
    ///   not arrive within [`Self::RECEIVE_TIMEOUT`] of the send, however many events arrive
    ///   while waiting.
    /// - `EIO` if the variable payload requested by the command has not been entirely
    ///   written to by its [`GmcCommand::init_variable_payload`] method, or if the reply carries
    ///   a status other than `NV_OK`.
    ///
    /// Error codes returned by the command and reply initializers, and by `on_event`, are
    /// propagated as-is.
    pub(crate) fn send_gmc_command<C>(
        &self,
        command: C,
        on_event: impl Fn(&GmcMessage<'_>) -> Result,
    ) -> Result<C::Reply>
    where
        C: CommandToGsp,
        C::Reply: MessageFromGsp,
        Error: From<C::InitError>,
        Error: From<<C::Reply as MessageFromGsp>::InitError>,
    {
        let mut inner = self.inner.lock();
        let seq = inner.send_gmc_command(command)?;

        inner.await_gmc_reply(seq, on_event)
    }

    /// Sends `command` to the GSP without waiting for a reply.
    ///
    /// # Errors
    ///
    /// - `EMSGSIZE` if the command does not fit in a single command queue element.
    /// - `ETIMEDOUT` if space does not become available within the timeout.
    /// - `EIO` if the variable payload requested by the command has not been entirely
    ///   written to by its [`CommandToGsp::init_variable_payload`] method.
    ///
    /// Error codes returned by the command initializer are propagated as-is.
    pub(crate) fn send_gmc_command_no_wait<C>(&self, command: C) -> Result
    where
        C: CommandToGsp<Reply = NoReply>,
        Error: From<C::InitError>,
    {
        self.inner.lock().send_gmc_command(command).map(|_| ())
    }
}

impl CmdqInner<'_> {
    /// Sends `command` to the GSP, and returns the sequence number of its element.
    ///
    /// Unlike RPC commands, GMC commands are never split: a command that does not fit in a single
    /// element is an error.
    ///
    /// # Errors
    ///
    /// - `EMSGSIZE` if the command does not fit in a single command queue element.
    /// - `ETIMEDOUT` if space does not become available within the timeout.
    /// - `EIO` if the variable payload requested by the command has not been entirely
    ///   written to by its [`CommandToGsp::init_variable_payload`] method.
    ///
    /// Error codes returned by the command initializer are propagated as-is.
    fn send_gmc_command<C>(&mut self, command: C) -> Result<u32>
    where
        C: CommandToGsp,
        Error: From<C::InitError>,
    {
        self.send_command_element(GmcCommandElement(command))
    }

    /// Receives the reply of type `R` to the command sent with sequence number `seq`, waiting up
    /// to [`Cmdq::RECEIVE_TIMEOUT`] from the call.
    ///
    /// Any GMC event that arrives first is passed to `on_event`, and any RPC message is logged.
    /// Neither extends the deadline.
    ///
    /// # Errors
    ///
    /// - `ETIMEDOUT` if the reply does not arrive before the deadline, however many other messages
    ///   arrive while waiting.
    /// - `EIO` if a message fails framing validation, or if the reply carries a status other than
    ///   `NV_OK`.
    ///
    /// Error codes returned by [`MessageFromGsp::read`] and by `on_event` are propagated as-is.
    fn await_gmc_reply<R: MessageFromGsp>(
        &mut self,
        seq: u32,
        on_event: impl Fn(&GmcMessage<'_>) -> Result,
    ) -> Result<R>
    where
        // This allows all error types, including `Infallible`, to be used for `R::InitError`.
        Error: From<R::InitError>,
    {
        let dev = self.dev;

        self.await_msg_with(|message| {
            let gmc_message = match message {
                GspParsedMessage::Gmc(gmc_message) => gmc_message,
                _ => {
                    message.log(dev);
                    return Err(ENOMSG);
                }
            };

            match gmc_message.is_reply_to(R::COMMAND, seq) {
                // Message is not the reply to our command, log it.
                None => {
                    on_event(&gmc_message)?;
                    return Err(ENOMSG);
                }
                // Reply has an error status.
                Some(status @ 1..) => {
                    dev_err!(
                        dev,
                        "GSP GMC: command {:?} failed with status {:#x}\n",
                        R::COMMAND,
                        status
                    );

                    return Err(EIO);
                }
                // Reply indicates the command has succeeded.
                Some(0) => (),
            }

            let mut sbuffer =
                SBufferIter::new_reader([gmc_message.contents.0, gmc_message.contents.1]);

            R::read(&mut sbuffer).map_err(|e| e.into()).inspect(|_| {
                if !sbuffer.is_empty() {
                    dev_warn!(dev, "GSP GMC reply {:?} has unprocessed data\n", R::COMMAND);
                }
            })
        })
    }
}
